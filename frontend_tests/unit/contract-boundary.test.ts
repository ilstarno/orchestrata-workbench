import { createRequire } from "node:module";
import { expect, it } from "vitest";
const require = createRequire(import.meta.url);
const { inspectText, inspectGenerated } =
  require("../../tooling/check-contract-boundary.cjs") as {
    inspectText(name: string, text: string): string[];
    inspectGenerated(files: [string, string][]): string[];
  };
const { splitContracts } =
  require("../../tooling/split-generated-contracts.cjs") as {
    splitContracts(text: string): Map<string, string>;
  };
const spec = () =>
  JSON.stringify(
    Object.fromEntries([
      ["open" + "api", ["3", "0", "0"].join(".")],
      ["paths", {}],
    ]),
  );
it("rejects specification content hidden behind alternate names, serialized strings and base64", () => {
  for (const [name, text] of [
    ["unrelated.data", spec()],
    ["embedded.js", `const payload = ${spec()}`],
    ["encoded.js", `const payload = ${JSON.stringify(spec())}`],
    [
      "base64.js",
      `const payload = ${JSON.stringify(Buffer.from(spec()).toString("base64"))}`,
    ],
    ["nested.json", `[${spec()}]`],
    ["OpenAPI.JSON", "{}"],
    ["metadata.yaml", ["OPEN" + "API: 3.0.0", "paths: {}"].join("\n")],
  ])
    expect(inspectText(name, text).length).toBeGreaterThan(0);
});
it("rejects embedded component schemas without a specification filename", () => {
  const value = Object.fromEntries([
    [
      "components",
      Object.fromEntries([
        ["schemas", { Example: { type: "object", properties: {} } }],
      ]),
    ],
  ]);
  expect(
    inspectText("renamed.json", JSON.stringify(value)).length,
  ).toBeGreaterThan(0);
  expect(
    inspectText("bundle.js", `const metadata = ${JSON.stringify(value)}`)
      .length,
  ).toBeGreaterThan(0);
});
it("permits ordinary domain records and enum collections", () => {
  expect(
    inspectText("input.json", '{"work_orders":[{"id":"a"}],"technicians":[]}'),
  ).toEqual([]);
  expect(
    inspectText("values.ts", 'export const values = ["string", "integer"];'),
  ).toEqual([]);
});
it("requires individual generated declarations and re-export-only barrels", () => {
  expect(
    inspectGenerated([
      ["Combined.ts", "export interface A {}\nexport interface B {}"],
    ]).length,
  ).toBeGreaterThan(0);
  expect(
    inspectGenerated([["orchestrata.ts", "export interface A {}"]]).length,
  ).toBeGreaterThan(0);
  expect(
    inspectGenerated([
      [
        "components.ts",
        "export interface components { schemas: { A: string } }",
      ],
    ]).length,
  ).toBeGreaterThan(0);
  expect(
    inspectGenerated([
      ["A.ts", "export type A = string"],
      ["orchestrata.ts", 'export type { A } from "./A"'],
    ]),
  ).toEqual([]);
});
it("splits authoritative generated declarations deterministically without retaining a bundled copy", () => {
  const input =
    'export interface paths {}\nexport interface operations {}\nexport interface components { schemas: { Example: { id: string }; Other: { value: components["schemas"]["Example"] } }; responses: never }\nexport type webhooks = Record<string, never>;\nexport type $defs = Record<string, never>;';
  const first = splitContracts(input),
    second = splitContracts(input);
  expect([...first]).toEqual([...second]);
  expect(first.has("schemas/Example.ts")).toBe(true);
  expect(first.has("schemas/Other.ts")).toBe(true);
  expect(inspectGenerated([...first])).toEqual([]);
  expect(first.get("orchestrata.ts")).not.toContain("interface");
  expect(() => splitContracts("export interface broken {")).toThrow();
});

it("checks complete generated bytes and source archives without Git metadata", async () => {
  const fs = await import("node:fs");
  const os = await import("node:os");
  const path = await import("node:path");
  const {
    check,
    inventory,
    inspectInventory,
  } = require("../../tooling/check-contract-boundary.cjs");
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "contract-archive-"));
  const generated = "frontend/src/shared/api/generated/";
  const declarations: [string, string][] = [
    ["Unused.ts", "export type Unused = string;"],
    ["orchestrata.ts", 'export type { Unused } from "./Unused";'],
  ];
  function write(name: string, text: string) {
    const file = path.join(root, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }
  try {
    for (const [name, text] of declarations) write(generated + name, text);
    write(
      "tooling/contract-inventory.json",
      JSON.stringify(inventory(declarations)),
    );
    write("frontend/node_modules/ignored.json", spec());
    write("frontend/.vite/ignored.json", spec());
    expect(fs.existsSync(path.join(root, ".git"))).toBe(false);
    expect(check(root).issues).toEqual([]);
    for (const name of [
      "frontend/src/payload.json",
      "frontend/public/payload.json",
      "frontend/dist/payload.json",
      "frontend/build-input.json",
    ]) {
      write(name, spec());
      expect(
        check(root).issues.some((issue: string) => issue.includes(name)),
      ).toBe(true);
      fs.unlinkSync(path.join(root, name));
    }
    fs.unlinkSync(path.join(root, generated, "Unused.ts"));
    expect(check(root).issues.join(" ")).toContain(
      "missing generated contract",
    );
    write(generated + "Unused.ts", "export type Unused = number;");
    expect(check(root).issues.join(" ")).toContain("stale generated contract");
    write(generated + "Unused.ts", declarations[0][1]);
    write(generated + "Stale.ts", "export type Stale = string;");
    expect(check(root).issues.join(" ")).toContain(
      "unexpected generated contract",
    );
    expect(inspectInventory(declarations, {})).not.toEqual([]);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
